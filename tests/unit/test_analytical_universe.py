"""Set equality is not currency, and an absent row is not a zero.

``UniverseCertification`` establishes that the contract list, the quote snapshot
and the Greeks snapshot name the same identities. On Aug 26 all three named
roughly five hundred contracts that had expired on Aug 25, carrying Aug-25
market timestamps, and on Aug 27 those were gone while roughly five hundred
Aug-26 contracts had replaced them. So the strongest universe state this
repository can award -- ``DEDICATED_CONTRACT_LIST_MATCHED_SNAPSHOT_UNIVERSE`` --
is compatible with a universe that is not this session's, and something has to
say so.

``src/adapters/thetadata/analytical_universe.py`` is that something. It
partitions one certified capture's listed universe into what an analytical
dataset could use and what it could not, with a named reason per exclusion and a
set hash per class.

**Nothing here is evidence about ThetaData.** The capture is generated by
``tests.synthetic_capture``, whose ``stale_expirations`` parameter exists
because the generator could not previously produce the behaviour this release
accounts for: every row went through the pricer, and a Black-Scholes input with
negative time is degenerate. The conclusions about the vendor live in
``docs/DATA_ELIGIBILITY.md`` and in the two live-capture fixtures.

These tests also hold the release's most important negative claim shut: the
certification report, its schema and its ``report_hash`` are **unchanged**. The
partition is a second report over the same verified bytes, so the two frozen
live-capture artifacts still reproduce.
"""

